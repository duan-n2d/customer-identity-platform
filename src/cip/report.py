"""Render docs/evaluation.md and the README results block from result files.

Every number in the documentation is generated here from ``results/*.json|csv``. Nothing is
typed by hand, so the docs cannot drift away from what the code actually measured.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def _md_table(df: pd.DataFrame, fmt: dict[str, str] | None = None) -> str:
    fmt = fmt or {}
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, row in df.iterrows():
        cells = [fmt.get(c, "{}").format(row[c]) for c in cols]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def headline(run: dict) -> str:
    last, first = run["days"][-1], run["days"][0]
    cfg = run["config"]["world"]
    stab = [d["stability"]["unchanged"] for d in run["days"][1:]]
    return "\n".join(
        [
            f"Synthetic Vietnamese customer data: **{cfg['n_persons']:,} people**, "
            f"{last['records']:,} source records across 4 systems, {cfg['days']} daily increments "
            f"(seed {cfg['seed']}).",
            "",
            "| Metric | Result |",
            "|---|---|",
            f"| Precision (linked record pairs that are the same person) | "
            f"**{_pct(last['precision'])}** |",
            f"| Recall on pairs that *can* be linked from the identifiers present | "
            f"**{_pct(last['linkable_recall'])}** |",
            f"| Share of true pairs that share any linking evidence (the data's ceiling) | "
            f"{_pct(last['linkable_share_of_true_pairs'])} |",
            f"| Person-ID stability, record level, day over day | "
            f"**{_pct(min(stab))} to {_pct(max(stab))}** |",
            f"| Same, with a naive ID (smallest record key of the cluster) | "
            f"{_pct(min(d['naive_min_key_unchanged'] for d in run['days'][1:]))} to "
            f"{_pct(max(d['naive_min_key_unchanged'] for d in run['days'][1:]))} |",
            f"| Day-0 load: {first['records']:,} records, train + match + IDs | "
            f"{first['seconds']:.0f} s |",
            f"| Daily run: ~{last['records']:,} records, full re-match | {last['seconds']:.0f} s |",
        ]
    )


def evaluation_md(run: dict, ablation: pd.DataFrame | None, bench: pd.DataFrame | None) -> str:
    days = pd.DataFrame(
        [
            {
                "day": d["day"],
                "records": d["records"],
                "people": d["active_ids"],
                "precision": d["precision"],
                "linkable recall": d["linkable_recall"],
                "ID unchanged": d["stability"]["unchanged"],
                "naive ID unchanged": d["naive_min_key_unchanged"],
                "new/merge/split": "/".join(
                    str(d["id_events"].get(k, 0)) for k in ("new", "merge", "split")
                ),
                "seconds": d["seconds"],
            }
            for d in run["days"]
        ]
    )
    final = run["final"]
    parts = [
        "# Evaluation",
        "",
        "> Generated by `cip report` from `results/`. Do not edit by hand.",
        "",
        "## What is measured and why",
        "",
        "The data is synthetic with a hidden ground truth, so every claim below is checkable. See "
        "[methodology](#method) for why *recall* is reported over **linkable pairs**.",
        "",
        "## Headline",
        "",
        headline(run),
        "",
        "## Day by day",
        "",
        _md_table(
            days,
            {
                "precision": "{:.4f}",
                "linkable recall": "{:.4f}",
                "ID unchanged": "{:.4f}",
                "naive ID unchanged": "{:.4f}",
                "seconds": "{:.1f}",
            },
        ),
        "",
        "`ID unchanged` is the share of records that kept their person ID since the previous day "
        "(day 0 has nothing to compare with). `naive ID` is what you get if the ID is just the "
        "smallest record key of the cluster: it changes whenever an earlier record is "
        "back-filled or two clusters merge.",
        "",
        "## Where the remaining errors come from",
        "",
        "False merges (record pairs linked that are different people), by trap:",
        "",
        _md_table(pd.DataFrame([final["false_merge_pairs_by_trap"]])),
        "",
        "Missed links (record pairs of one person left apart), by trap:",
        "",
        _md_table(pd.DataFrame([final["missed_pairs_by_trap"]])),
        "",
        f"Largest cluster: {final['errors']['largest_cluster']} records. People split across "
        f"clusters: {final['errors']['people_split_across_clusters']:,} of "
        f"{final['errors']['true_persons']:,}.",
        "",
    ]
    if ablation is not None:
        parts += [
            "## Ablation: what each component is worth",
            "",
            "3,000 people per world, mean over the seeds in `seeds` (columns ending in `_sd` are the "
            "standard deviation across seeds). One component changed at a time. Rows 1-6 add "
            "components cumulatively; the rest remove or add one component to the default profile. "
            "Test seeds 7, 21, 22; dev seeds are in `results/ablation_dev.csv`.",
            "",
            _md_table(
                ablation,
                {
                    "precision": "{:.4f}",
                    "linkable_recall": "{:.4f}",
                    "linkable_f1": "{:.4f}",
                    "precision_sd": "{:.4f}",
                    "linkable_recall_sd": "{:.4f}",
                    "linkable_f1_sd": "{:.4f}",
                    "false_merge_pairs": "{:.0f}",
                    "households": "{:.0f}",
                    "recycled": "{:.0f}",
                    "common_name": "{:.0f}",
                },
            ),
            "",
        ]
    if bench is not None:
        parts += [
            "## Scale",
            "",
            "Day-0 pipeline (landing, staging, hubs, model training, scoring, rules, clustering, "
            "IDs) "
            "on one machine, DuckDB, single process:",
            "",
            _md_table(bench, {"seconds": "{:.1f}", "records_per_second": "{:,.0f}"}),
            "",
        ]
    parts += [
        "## Method",
        "",
        "* **Precision** is pairwise: of the record pairs placed in one cluster, the share that "
        "really are the same person. A false merge shows a customer another customer's data, so "
        "precision is the metric the default profile optimises.",
        "* **Linkable recall.** Two records of one person can only be linked if they share some "
        "evidence (phone, email, date of birth). In this data most true pairs share nothing, "
        "and no "
        "algorithm can find them; recall over *all* true pairs mostly measures the data. We report "
        "recall over the linkable pairs, and the linkable share separately.",
        "* **Configuration** used for this run:",
        "",
        "```json",
        json.dumps(run["config"], indent=2, default=str),
        "```",
    ]
    return "\n".join(parts) + "\n"


def update_readme(readme: Path, block: str) -> None:
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{readme} has no {START} ... {END} markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    readme.write_text(f"{head}{START}\n{block}\n{END}{tail}", encoding="utf-8", newline="\n")
